import fs from "fs";
import fsp from "fs/promises";
import path from "path";
import { getUploadsDir } from "@/lib/storage";
import { prisma } from "@/lib/prisma";

/** Below the 10 MB the proxy buffers per request (proxyClientMaxBodySize), leaving room for the multipart envelope. */
export const MAX_ATTACHMENT_BYTES = 8 * 1024 * 1024;

/** Extensions accepted as card attachments, with the type the download is served as. */
export const ATTACHMENT_TYPES: Record<string, string> = {
  pdf: "application/pdf",
  png: "image/png",
  jpg: "image/jpeg",
  jpeg: "image/jpeg",
  gif: "image/gif",
  webp: "image/webp",
  txt: "text/plain",
  csv: "text/csv",
  doc: "application/msword",
  docx: "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
  xls: "application/vnd.ms-excel",
  xlsx: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
  ppt: "application/vnd.ms-powerpoint",
  pptx: "application/vnd.openxmlformats-officedocument.presentationml.presentation",
  zip: "application/zip",
};

export const attachmentExtension = (name: string) => path.extname(name).slice(1).toLowerCase();

/** Directory of card attachments, created on first use. */
export function attachmentsDir() {
  const dir = path.join(getUploadsDir(), "crm");
  fs.mkdirSync(dir, { recursive: true });
  return dir;
}

/** Disk path of a stored attachment; `fileName` is generated by us, basename() is a second guard. */
export const attachmentPath = (fileName: string) => path.join(attachmentsDir(), path.basename(fileName));

export const attachmentSelect = { id: true, originalName: true, mimeType: true, size: true, createdAt: true, uploadedBy: { select: { name: true } } } as const;

/** Deletes a card; its attachment rows go with it (cascade) and their files are removed here. Returns the card. */
export async function deleteCardWithFiles(id: string) {
  const files = await prisma.crmAttachment.findMany({ where: { cardId: id }, select: { fileName: true } });
  const card = await prisma.crmCard.delete({ where: { id } });
  await Promise.all(files.map((f) => fsp.rm(attachmentPath(f.fileName), { force: true })));
  return card;
}

/** Deletes a pipeline with its stages and cards (cascade) and removes the cards' attachment files. */
export async function deletePipelineWithFiles(id: string) {
  const files = await prisma.crmAttachment.findMany({ where: { card: { stage: { pipelineId: id } } }, select: { fileName: true } });
  await prisma.crmPipeline.delete({ where: { id } });
  await Promise.all(files.map((f) => fsp.rm(attachmentPath(f.fileName), { force: true })));
}
